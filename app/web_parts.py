"""Демонстрационные кандидаты запчастей «из интернета» без привязки к магазину/бренду.

Реальный веб-поиск пока не вызывается: список строится по запросу и коду поломки,
чтобы механик мог выбрать позицию для заявки. Только названия деталей, не процессы.
"""

from __future__ import annotations

import re

_NODE_HINTS: list[tuple[re.Pattern[str], list[str]]] = [
    (
        re.compile(r"сцеплен|выжимн|корзин|диск сцеп|f06", re.I),
        [
            "Диск сцепления ведомый (универсальный типоразмер)",
            "Корзина сцепления в сборе",
            "Подшипник выжимной сцепления",
            "Вилка выключения сцепления",
            "Цилиндр рабочий привода сцепления",
        ],
    ),
    (
        re.compile(r"коробк|передач|кпп|синхрон|f07", re.I),
        [
            "Подшипник первичного вала КПП",
            "Подшипник вторичного вала КПП",
            "Синхронизатор (комплект)",
            "Прокладка картера коробки передач",
            "Сальник хвостовика КПП",
        ],
    ),
    # F08 в каталоге mock — «Дизельная топливоподача» (не клапаны).
    (
        re.compile(r"топлив|форсун|тнвд|топливоподач|f10|f04|f08", re.I),
        [
            "Форсунка топливная",
            "Фильтр тонкой очистки топлива",
            "Фильтр грубой очистки топлива",
            "Прокладка крышки ТНВД",
            "Трубка высокого давления топлива",
        ],
    ),
    (
        re.compile(r"клапан|зазор|гбц|распред", re.I),
        [
            "Прокладка головки блока цилиндров",
            "Клапан впускной (комплект)",
            "Клапан выпускной (комплект)",
            "Маслосъёмные колпачки клапанов",
            "Регулировочная шайба зазора клапанов",
        ],
    ),
    (
        re.compile(r"масл|давлен|насос масл|фильтр масл|f02", re.I),
        [
            "Насос масляный двигателя",
            "Фильтр масляный",
            "Датчик давления масла",
            "Прокладка масляного насоса",
            "Радиатор масляный",
        ],
    ),
]

_GENERIC = [
    "Ремкомплект уплотнений узла",
    "Крепёж узла (болты/гайки, комплект)",
    "Прокладка стыка узла",
]


def internet_spare_candidates(
    query: str,
    *,
    anomaly_type: str | None = None,
    anomaly_title: str | None = None,
    limit: int = 8,
) -> list[dict]:
    blob = " ".join(
        bit for bit in (query or "", anomaly_type or "", anomaly_title or "") if bit
    ).strip()
    names: list[str] = []
    for pattern, items in _NODE_HINTS:
        if pattern.search(blob):
            names.extend(items)
            break
    if not names:
        node = (anomaly_title or query or "узел").strip()
        # Не подставлять длинный/процессный текст в имя детали.
        node = re.sub(r"(?i)^(проверить|отрегулировать|заменить)\b.*", "узел", node)
        node = node[:40].strip() or "узел"
        names = [
            f"Деталь узла «{node}» (универсальный аналог)",
            f"Ремкомплект для «{node}»",
            *_GENERIC,
        ]
    else:
        names = names + _GENERIC[:2]

    out: list[dict] = []
    seen: set[str] = set()
    for index, name in enumerate(names):
        key = name.casefold()
        if key in seen:
            continue
        seen.add(key)
        out.append(
            {
                "id": f"web-{index + 1}",
                "label": name,
                "source": "web_stub",
                "source_label": "Интернет (демонстрация, без магазина и производителя)",
                "excerpt": (
                    "Кандидат-деталь для выбора в заявку. Реальный поиск по открытым "
                    "источникам будет позже; сейчас — типовая позиция по поломке."
                ),
                "selectable": True,
            }
        )
        if len(out) >= limit:
            break
    return out
