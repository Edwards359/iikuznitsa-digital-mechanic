from app.rag import is_contents_page


def test_toc_pages_detected() -> None:
    toc = (
        "Содержание\n"
        "Введение ........................................................................ 8\n"
        "1 Общие сведения ................................................................ 10\n"
        "1011. Насос масляный ........................................................ 150\n"
        "1011. Крышка масляного насоса ........................................ 152\n"
        "1012. Фильтр масляный ....................................................... 160\n"
    )
    assert is_contents_page(toc) is True


def test_procedure_page_not_toc() -> None:
    body = (
        "Перед регулировкой зазора клапанов двигатель должен быть холодным. "
        "Проверить тепловой зазор впускных и выпускных клапанов. "
        "Момент затяжки гаек по таблице."
    )
    assert is_contents_page(body) is False
